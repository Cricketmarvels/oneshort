"""Plain-language reasons for rating changes, built only from the stored numbers.

Nothing here is generated by a language model; every sentence is a template filled from
the verified scorecard and the actual before/after ratings.
"""

from typing import Any

LABEL = {"bat": "Batting", "bowl": "Bowling", "field": "Fielding", "impact": "Match impact"}
_MIN_DELTA = 2.0


def _overs(balls: int) -> str:
    return f"{balls // 6}.{balls % 6}" if balls % 6 else str(balls // 6)


def match_reasons(
    deltas: dict[str, float],
    lines: dict[str, Any],
    opponent_name: str,
    stronger_opponent: bool,
    result: str,
) -> list[str]:
    reasons: list[str] = []
    for d in ("bat", "bowl", "field"):
        delta = deltas.get(d)
        if delta is None or abs(delta) < _MIN_DELTA:
            continue
        sign = "+" if delta > 0 else "−"
        if d == "bat" and (b := lines.get("bat")):
            what = f"{b['runs']}{'*' if not b['out'] else ''} off {b['balls']}"
        elif d == "bowl" and (b := lines.get("bowl")):
            what = f"{b['wickets']}/{b['runs']} in {_overs(b['balls'])} overs"
        elif d == "field" and (f := lines.get("field")):
            bits = [
                f"{n} {one if n == 1 else many}"
                for n, one, many in (
                    (f["catches"], "catch", "catches"),
                    (f["run_outs"], "run-out", "run-outs"),
                    (f["stumpings"], "stumping", "stumpings"),
                )
                if n
            ]
            what = ", ".join(bits) or "no dismissals"
        else:
            continue
        text = f"{LABEL[d]} {sign}{abs(round(delta))}: {what} against {opponent_name}"
        if delta > 0 and stronger_opponent:
            text += ", a higher-rated side"
        reasons.append(text)
    if result in ("won", "lost") and abs(deltas.get("impact", 0.0)) >= _MIN_DELTA:
        reasons.append("Team win added to match impact" if result == "won" else "Team loss reduced match impact")
    return reasons


def trend_summary(history: list[dict[str, Any]]) -> list[str]:
    """Summarise recent history entries (newest first) into a few sentences."""
    if not history:
        return []
    total = {d: 0.0 for d in ("bat", "bowl", "field")}
    overall = 0.0
    for h in history:
        overall += h["after"]["overall"] - h["before"]["overall"]
        for d in total:
            total[d] += h["after"][d] - h["before"][d]
    n = len(history)
    out = []
    direction = "increased" if overall > 0 else "decreased"
    if abs(overall) >= _MIN_DELTA:
        main = max(total, key=lambda k: abs(total[k]))
        out.append(
            f"Overall rating {direction} by {abs(round(overall))} over your last {n} verified match"
            f"{'' if n == 1 else 'es'}, mostly from {LABEL[main].lower()} ({'+' if total[main] >= 0 else '−'}"
            f"{abs(round(total[main]))})."
        )
    else:
        out.append(f"Overall rating has held steady over your last {n} verified match{'' if n == 1 else 'es'}.")
    for reason in (history[0].get("reasons") or [])[:2]:
        out.append(f"Last match — {reason}.")
    return out
